"""AI 前沿咨询 Agent —— Prompt 模板（搜索意图 + 动态搜索词 + LLM 摘要）"""

# ═══════════════════════════════════════════
# 搜索意图（替代硬编码 query，由 understand 节点动态生成搜索词）
# ═══════════════════════════════════════════

DAILY_SEARCH_INTENT = "搜索昨天AI/人工智能领域的重大新闻"

WEEKLY_SEARCH_INTENT = "搜索最近一周AI/人工智能领域的重大新闻"

# ═══════════════════════════════════════════
# Understand 节点 Prompt（分析意图 → 生成搜索词 + 时效）
# ═══════════════════════════════════════════

UNDERSTAND_QUERY_PROMPT = """分析以下搜索意图："{search_intent}"

当前日期：{today_str} {day_of_week}

请完成三个任务：
1. 简洁总结要搜索什么内容
2. 判断信息时效性要求，转换为具体天数
   - "今天/今日/今天发生的" → 1天
   - "最近N天" → N天
   - "最近一周/过去7天" → 7天
   - "最近一月/这个月" → 30天
   - 没有明确时间要求 → 不限
3. 生成最适合搜索的关键词（必须使用英文！Tavily英文索引质量远好于中文，中文搜索会返回过期内容）
   - 如果有时效要求，搜索词中请自然地加入时间限定词（如 "today"、"July 27 2026" 等）

格式：
理解：[用户需求总结]
时效：[仅输出数字，如 1、7、30，或"不限"]
搜索词：[最佳搜索关键词]"""


# ═══════════════════════════════════════════
# LLM 摘要 Prompt（日报/周报共用，report_type 由调用方决定）
# ═══════════════════════════════════════════

SUMMARIZE_PROMPT = """当前日期：{today_str}（这是"今天"的准确日期，请以此为准）

以下是一份新闻搜索的原始结果，里面可能混有与 AI 无关的条目、图片说明文字、重复标题和港台繁体内容：

搜索结果：
{search_results}

请把这些搜索结果整理成一份【纯新闻播报】，严格遵循以下要求：

【语言】
1. 全文必须使用简体中文。搜索原文若为繁体中文（如港台媒体），必须转换为简体中文，不得直接搬用繁体字。

【内容与取舍】
2. 只播报新闻本身，不要任何开场白、结束语、评论或话术（禁止"好的""根据搜索结果""如需更多资讯""建议您…"等字样）。
3. 只保留与 AI / 人工智能 / 大模型 / AI 硬件或政策直接相关的新闻；剔除与 AI 无关的擦边条目（如纯游戏、纯娱乐、普通消费电子涨价等）。
4. 忽略搜索原文中的图片说明文字、图片 alt 文本、纯英文解释句、重复出现的标题，不把它们写进结果。

【数量】
5. 日报最多 5 条、周报最多 10 条；若搜索结果中有效新闻不足上限，有多少报多少（最少 1 条），不要凑数也不要编造。

【格式】
6. 每条新闻按以下结构输出（用 --- 分隔），按发布时间从新到旧排列，时间未知的排在最后：

### N. 标题
- 内容摘要：一句话或两句话概括新闻要点
- 发布时间：YYYY年MM月DD日（原文未标注时写"时间未知"）
- 来源：来源名称 (URL)"""

# 兼容旧引用（后续可删除）
DAILY_SUMMARIZE_PROMPT = SUMMARIZE_PROMPT
WEEKLY_SUMMARIZE_PROMPT = SUMMARIZE_PROMPT
